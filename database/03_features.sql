USE PawPrintDB;
GO
IF COL_LENGTH('dbo.Users','Role') IS NULL
ALTER TABLE dbo.Users ADD Role NVARCHAR(20) NOT NULL DEFAULT 'owner' CHECK(Role IN ('owner','admin'));
IF OBJECT_ID('dbo.RefreshSessions','U') IS NULL
CREATE TABLE dbo.RefreshSessions (
 TokenHash CHAR(64) PRIMARY KEY, UserId UNIQUEIDENTIFIER NOT NULL REFERENCES dbo.Users(Id),
 ExpiresAt DATETIME2(3) NOT NULL, CreatedAt DATETIME2(3) NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
IF OBJECT_ID('dbo.Products','U') IS NULL
CREATE TABLE dbo.Products (
 Id UNIQUEIDENTIFIER PRIMARY KEY DEFAULT NEWID(), Name NVARCHAR(160) NOT NULL,
 Category NVARCHAR(80) NOT NULL, Description NVARCHAR(2000) NULL,
 Price DECIMAL(12,0) NOT NULL CHECK(Price >= 0), Currency CHAR(3) NOT NULL DEFAULT 'VND',
 Stock INT NOT NULL CHECK(Stock >= 0), ImageUrl NVARCHAR(500) NULL,
 IsActive BIT NOT NULL DEFAULT 1
);
IF OBJECT_ID('dbo.AuditLogs','U') IS NULL
CREATE TABLE dbo.AuditLogs (
 Id BIGINT IDENTITY PRIMARY KEY, ActorId UNIQUEIDENTIFIER NOT NULL,
 Action NVARCHAR(80) NOT NULL, EntityId UNIQUEIDENTIFIER NOT NULL,
 CreatedAt DATETIME2(3) NOT NULL DEFAULT SYSUTCDATETIME()
);
IF OBJECT_ID('dbo.CartItems','U') IS NULL
CREATE TABLE dbo.CartItems (
 UserId UNIQUEIDENTIFIER NOT NULL REFERENCES dbo.Users(Id),
 ProductId UNIQUEIDENTIFIER NOT NULL REFERENCES dbo.Products(Id),
 Quantity INT NOT NULL CHECK(Quantity BETWEEN 1 AND 99),
 PRIMARY KEY(UserId, ProductId)
);
IF OBJECT_ID('dbo.Orders','U') IS NULL
CREATE TABLE dbo.Orders (
 Id UNIQUEIDENTIFIER PRIMARY KEY, UserId UNIQUEIDENTIFIER NOT NULL REFERENCES dbo.Users(Id),
 RequestKey UNIQUEIDENTIFIER NOT NULL, Recipient NVARCHAR(100) NOT NULL,
 Phone NVARCHAR(30) NOT NULL, Address NVARCHAR(500) NOT NULL,
 Total DECIMAL(14,0) NOT NULL, Status NVARCHAR(30) NOT NULL DEFAULT 'pending',
 PaymentMethod NVARCHAR(20) NOT NULL DEFAULT 'cod',
 CreatedAt DATETIME2(3) NOT NULL DEFAULT SYSUTCDATETIME(),
 CONSTRAINT UQ_Orders_Request UNIQUE(UserId,RequestKey)
);
IF OBJECT_ID('dbo.OrderItems','U') IS NULL
CREATE TABLE dbo.OrderItems (
 OrderId UNIQUEIDENTIFIER NOT NULL REFERENCES dbo.Orders(Id),
 ProductId UNIQUEIDENTIFIER NOT NULL REFERENCES dbo.Products(Id),
 ProductName NVARCHAR(160) NOT NULL, UnitPrice DECIMAL(12,0) NOT NULL,
 Quantity INT NOT NULL CHECK(Quantity > 0), PRIMARY KEY(OrderId,ProductId)
);
GO
